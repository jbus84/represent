project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from represent.modular_dataset_builder import ModularDatasetBuilder  # noqa: E402
from represent.target_generators.factory import TargetGeneratorFactory  # noqa: E402

# Import preset configurations from build_label_set.py
sys.path.insert(0, str(project_root / "scripts"))
from build_label_set import LABEL_SET_PRESETS  # noqa: E402


def is_outright_contract(symbol: str) -> bool:
    """
    Check if symbol is an outright contract (not a spread).

    Outright contracts are single instruments without spread notation.
    Spread instruments contain '-' or other combination characters.

    Args:
        symbol: The symbol to check

    Returns:
        True if outright contract, False if spread instrument
    """
    symbol_str = str(symbol)
    # Filter out spread instruments that contain '-', '/', or other spread indicators
    return "-" not in symbol_str and "/" not in symbol_str and "+" not in symbol_str


def load_and_process_dbn_files(
    dbn_directory: Path,
    output_dir: Path,
    target_generators: list,
    preset_name: str = None,
    chunk_size: int = 100000,
    exclude_spreads: bool = True,
) -> dict[str, Any]:
    """
    Load DBN files using streaming approach, split by symbol, apply labeling, and create comprehensive datasets.

    This implements the symbol-split-merge approach with memory-efficient streaming:
    1. Process each DBN file in chunks and split by symbol
    2. For each symbol, merge data across all DBN files using streaming
    3. Apply target generation to create labels in chunks
    4. Save comprehensive symbol datasets with all DBN columns + labels
    """
    try:
        import databento as db
    except ImportError as err:
        raise ImportError(
            "databento library is required for DBN processing. Install with: uv add databento"
        ) from err

    print(f"📂 Processing DBN files from: {dbn_directory} (streaming mode)")

    # Find all DBN files
    dbn_files = list(dbn_directory.glob("*.dbn*"))
    if not dbn_files:
        raise FileNotFoundError(f"No DBN files found in {dbn_directory}")

    print(f"📊 Found {len(dbn_files)} DBN files")
    print(f"🔄 Using streaming chunks of {chunk_size:,} samples for memory efficiency")

    # Phase 1: Process each DBN file in chunks and collect symbol data
    symbol_files: dict[str, list[Path]] = {}  # symbol -> list of temp file paths
    temp_dir = output_dir / "temp_symbol_chunks"
    temp_dir.mkdir(parents=True, exist_ok=True)

    for i, dbn_file in enumerate(dbn_files, 1):
        print(f"📖 [{i}/{len(dbn_files)}] Processing {dbn_file.name}")

        try:
            # Load DBN file
            data = db.read_dbn(str(dbn_file))
            df = data.to_df()

            if len(df) == 0:
                print("   ⚠️  Empty file, skipping")
                continue

            print(f"   📊 File contains {len(df):,} total samples")

            # Process in chunks to manage memory
            total_processed = 0
            chunk_num = 0

            for chunk_start in range(0, len(df), chunk_size):
                chunk_end = min(chunk_start + chunk_size, len(df))
                df_chunk = df.iloc[chunk_start:chunk_end]

                # Convert chunk to polars and ensure required columns
                df_pl = pl.from_pandas(df_chunk)

                # Check for symbol column (only need to check once per file)
                if chunk_num == 0:
                    symbol_col = None
                    for col in ["symbol", "sym"]:
                        if col in df_pl.columns:
                            symbol_col = col
                            break

                    if symbol_col is None:
                        print("   ⚠️  No symbol column found, skipping file")
                        break

                # Ensure we have price data
                if "bid_px_00" in df_pl.columns and "ask_px_00" in df_pl.columns:
                    # Calculate mid price if not present
                    if "mid_price" not in df_pl.columns:
                        df_pl = df_pl.with_columns(
                            [((pl.col("bid_px_00") + pl.col("ask_px_00")) / 2.0).alias("mid_price")]
                        )
                elif "price" in df_pl.columns:
                    df_pl = df_pl.rename({"price": "mid_price"})
                else:
                    if chunk_num == 0:
                        print("   ⚠️  No price data found, skipping file")
                        break
                    continue

                # Ensure timestamp column
                if "ts_event" not in df_pl.columns:
                    if "ts_recv" in df_pl.columns:
                        df_pl = df_pl.rename({"ts_recv": "ts_event"})
                    else:
                        if chunk_num == 0:
                            print("   ⚠️  No timestamp column found, skipping file")
                            break
                        continue

                # Split by symbol within this chunk
                symbols = df_pl.select(symbol_col).unique().to_series().to_list()

                # Filter symbols based on exclude_spreads setting
                if exclude_spreads:
                    outright_symbols = [s for s in symbols if is_outright_contract(s)]
                    spread_symbols = [s for s in symbols if not is_outright_contract(s)]
                    symbols_to_process = outright_symbols

                    if chunk_num == 0:
                        print(
                            f"   📋 Found {len(symbols)} total symbols in file: {len(outright_symbols)} outright, {len(spread_symbols)} spreads"
                        )
                        if outright_symbols:
                            print(
                                f"   ✅ Processing outright contracts: {', '.join(str(s) for s in outright_symbols[:5])}{'...' if len(outright_symbols) > 5 else ''}"
                            )
                        if spread_symbols:
                            print(
                                f"   ⏭️  Skipping spread instruments: {', '.join(str(s) for s in spread_symbols[:3])}{'...' if len(spread_symbols) > 3 else ''}"
                            )
                else:
                    symbols_to_process = symbols
                    if chunk_num == 0:
                        print(
                            f"   📋 Processing all {len(symbols)} symbols: {', '.join(str(s) for s in symbols[:5])}{'...' if len(symbols) > 5 else ''}"
                        )

                for symbol in symbols_to_process:
                    symbol_df = df_pl.filter(pl.col(symbol_col) == symbol)

                    if len(symbol_df) < 100:  # Skip symbols with too little data in this chunk
                        continue

                    # Standardize symbol column name
                    if symbol_col != "symbol":
                        symbol_df = symbol_df.rename({symbol_col: "symbol"})

                    # Save chunk to temporary file
                    chunk_filename = f"{dbn_file.stem}_{symbol}_chunk_{chunk_num:04d}.parquet"
                    chunk_path = temp_dir / chunk_filename
                    symbol_df.write_parquet(chunk_path)

                    if symbol not in symbol_files:
                        symbol_files[symbol] = []
                    symbol_files[symbol].append(chunk_path)

                total_processed += len(df_chunk)
                chunk_num += 1

                # Clear chunk from memory
                del df_chunk, df_pl

                if chunk_num % 10 == 0:
                    print(
                        f"   🔄 Processed {total_processed:,}/{len(df):,} samples ({100 * total_processed / len(df):.1f}%)"
                    )

            print(f"   ✅ Completed processing {total_processed:,} samples in {chunk_num} chunks")

            # Clear full dataframe from memory
            del df

        except Exception as e:
            print(f"   ❌ Error processing {dbn_file.name}: {e}")
            continue

    if not symbol_files:
        raise ValueError("No valid symbol data extracted from DBN files")

    print(f"\n📊 Phase 1 Complete: Collected streaming chunks for {len(symbol_files)} symbols")

    # Phase 2: Merge symbol chunks and apply labeling using streaming
    builder = ModularDatasetBuilder(target_generators, verbose=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    created_datasets = []
    total_samples = 0

    for symbol, chunk_files in symbol_files.items():
        print(f"\n🎯 Processing symbol: {symbol}")
        print(f"   📊 Merging {len(chunk_files)} chunk files using streaming")

        try:
            # Merge all chunk files for this symbol using streaming
            merged_dfs = []
            total_chunk_samples = 0

            for chunk_file in chunk_files:
                chunk_df = pl.read_parquet(chunk_file)
                merged_dfs.append(chunk_df)
                total_chunk_samples += len(chunk_df)

                # Process in batches to avoid excessive memory usage
                if len(merged_dfs) >= 10:  # Merge every 10 chunks
                    batch_merged = pl.concat(merged_dfs, how="vertical")
                    merged_dfs = [batch_merged]

            # Final merge of all chunks for this symbol
            merged_df = pl.concat(merged_dfs, how="vertical")
            
            # Sort by event time for determinism
            if "ts_event" in merged_df.columns:
                merged_df = merged_df.sort("ts_event")
            
            # De-duplicate rows to avoid duplicated index keys when indexing onto inputs
            before_len = len(merged_df)
            dedup_subset = None
            if "ts_event" in merged_df.columns:
                # Prefer most-granular unique keys if available
                if "seqnum" in merged_df.columns:
                    dedup_subset = ["ts_event", "seqnum"]
                elif "ts_recv" in merged_df.columns:
                    dedup_subset = ["ts_event", "ts_recv"]
                elif "symbol" in merged_df.columns:
                    dedup_subset = ["ts_event", "symbol"]
                else:
                    dedup_subset = ["ts_event"]
            
            if dedup_subset is not None:
                merged_df = merged_df.unique(subset=dedup_subset, maintain_order=True)
            else:
                # Fallback: drop exact duplicate rows
                merged_df = merged_df.unique(maintain_order=True)
            
            after_len = len(merged_df)
            dropped = before_len - after_len

            print(
                f"   📊 Merged dataset: {len(merged_df):,} samples from {len(chunk_files)} chunks"
            )
            if dropped > 0:
                print(f"   🧹 De-duplicated {dropped:,} rows using subset={dedup_subset}")

            if len(merged_df) < 5000:  # Skip symbols with insufficient data
                print(f"   ⚠️  Insufficient data ({len(merged_df)} samples), skipping")
                continue

            # Apply target generation (this creates the labels)
            labeled_dataset = builder.build_dataset(merged_df)

            # Clear merged dataframes from memory
            del merged_df, merged_dfs

            # Create output filename
            timestamp = __import__("datetime").datetime.now().strftime("%Y%m%d_%H%M%S")
            if preset_name:
                filename = f"{symbol}_{preset_name}_dataset_{timestamp}.parquet"
            else:
                filename = f"{symbol}_labeled_dataset_{timestamp}.parquet"

            output_path = output_dir / filename

            # Select only merge keys + target columns (targets-only output)
            key_cols = [c for c in ["ts_event", "symbol", "ts_recv"] if c in labeled_dataset.columns]
            original_cols = ["symbol", "mid_price", "ts_event"]
            target_cols = [
                col
                for col in labeled_dataset.columns
                if col not in original_cols
                and not col.startswith(("bid_", "ask_", "ts_", "size_", "ct_"))
            ]
            targets_only_cols = list(dict.fromkeys(key_cols + target_cols))  # preserve order, dedupe
            targets_only_df = labeled_dataset.select(targets_only_cols)

            # Save targets-only dataset
            builder.save_dataset(targets_only_df, output_path)

            print(f"   ✅ Saved: {output_path}")
            print(
                f"   📊 Final targets-only dataset: {len(targets_only_df):,} samples, {len(targets_only_df.columns)} columns"
            )

            # Report on target columns created
            if target_cols:
                print(f"   🎯 Target columns: {', '.join(target_cols)}")

            created_datasets.append(
                {
                    "symbol": symbol,
                    "path": output_path,
                    "samples": len(targets_only_df),
                    "columns": len(targets_only_df.columns),
                    "targets": target_cols,
                }
            )
            total_samples += len(targets_only_df)

        except Exception as e:
            print(f"   ❌ Error processing symbol {symbol}: {e}")
            continue
        finally:
            # Clean up chunk files for this symbol
            for chunk_file in chunk_files:
                try:
                    chunk_file.unlink()
                except Exception:
                    pass  # Ignore cleanup errors

    # Clean up temporary directory
    try:
        temp_dir.rmdir()
        print("\n🧹 Cleaned up temporary chunk files")
    except Exception:
        print(f"\n⚠️  Could not remove temporary directory: {temp_dir}")

    return {
        "created_datasets": created_datasets,
        "total_symbols": len(created_datasets),
        "total_samples": total_samples,
        "output_directory": str(output_dir),
        "streaming_chunks_used": chunk_size,
    }


def main():
    parser = argparse.ArgumentParser(
        description="Build symbol datasets from DBN files with labels",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Use preset configuration
  python scripts/build_symbol_datasets_from_dbn.py --preset mfe_analysis --dbn-dir /path/to/dbn --output-dir /path/to/output

  # Use custom configuration file
  python scripts/build_symbol_datasets_from_dbn.py --config config.yaml --dbn-dir /path/to/dbn --output-dir /path/to/output

  # List available presets
  python scripts/build_symbol_datasets_from_dbn.py --list-presets
        """,
    )

    parser.add_argument(
        "--preset",
        choices=LABEL_SET_PRESETS.keys(),
        help="Use a predefined label set configuration",
    )
    parser.add_argument("--config", type=Path, help="Path to custom configuration YAML file")
    parser.add_argument(
        "--list-presets", action="store_true", help="List available preset configurations"
    )

    parser.add_argument(
        "--dbn-dir",
        type=Path,
        required=False,
        help="Directory containing DBN files to process",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("/Users/danielfisher/data/databento/symbol_datasets"),
        help="Output directory for symbol datasets",
    )
    parser.add_argument(
        "--chunk-size",
        type=int,
        default=100000,
        help="Chunk size for streaming processing (default: 100,000 samples per chunk)",
    )
    parser.add_argument(
        "--include-spreads",
        action="store_true",
        help="Include spread instruments in processing (default: exclude spreads, process only outright contracts)",
    )

    args = parser.parse_args()

    # Handle special commands
    if args.list_presets:
        print("\n🎯 Available Label Set Presets:")
        print("=" * 50)
        for key, preset in LABEL_SET_PRESETS.items():
            print(f"\n{key}:")
            print(f"  Name: {preset['name']}")
            print(f"  Description: {preset['description']}")
            print(f"  Generators: {len(preset['generators'])}")
        return

    if not args.dbn_dir:
        parser.error("--dbn-dir is required when not using --list-presets")

    # Determine configuration
    if args.preset:
        config = LABEL_SET_PRESETS[args.preset]
        print(f"🎯 Using preset: {args.preset}")
        preset_name = args.preset
    elif args.config:
        with open(args.config) as f:
            config = yaml.safe_load(f)
        print(f"📄 Using config file: {args.config}")
        preset_name = None
    else:
        parser.error("Must specify either --preset or --config")

    print(f"\n🎯 Building Symbol Datasets: {config['name']}")
    print(f"📝 {config['description']}")
    print("=" * 60)

    # Create generators from configuration
    generators = []
    for gen_config in config["generators"]:
        gen_config_copy = gen_config.copy()  # Don't modify original
        gen_type = gen_config_copy.pop("type")
        generator = TargetGeneratorFactory.create(gen_type, **gen_config_copy)
        generators.append(generator)

    print(f"🔧 Created {len(generators)} target generators")

    # Process DBN files and create symbol datasets
    try:
        results = load_and_process_dbn_files(
            dbn_directory=args.dbn_dir,
            output_dir=args.output_dir,
            target_generators=generators,
            preset_name=preset_name,
            chunk_size=args.chunk_size,
            exclude_spreads=not args.include_spreads,
        )

        print("\n🎉 SUCCESS!")
        print("=" * 60)
        print(f"📊 Processed {results['total_symbols']} symbols using streaming approach")
        print(f"📈 Total samples: {results['total_samples']:,}")
        print(f"🔄 Chunk size used: {results['streaming_chunks_used']:,} samples per chunk")
        if not args.include_spreads:
            print("📋 Symbol filter: Outright contracts only (spreads excluded)")
        else:
            print("📋 Symbol filter: All symbols included (outright contracts + spreads)")
        print(f"📁 Output directory: {results['output_directory']}")
        print("\n📋 Created datasets:")

        for dataset in results["created_datasets"]:
            print(
                f"  • {dataset['symbol']}: {dataset['samples']:,} samples, {dataset['columns']} columns"
            )
            if dataset["targets"]:
                print(f"    🎯 Targets: {', '.join(dataset['targets'])}")

        print("\n🚀 Symbol datasets ready for ML training!")
        print("💡 Each dataset contains ALL original DBN columns PLUS the generated target labels")
        print(
            f"🧠 Memory-efficient: Processed using {results['streaming_chunks_used']:,}-sample chunks"
        )
        if not args.include_spreads:
            print(
                "🎯 Clean data: Only outright contracts processed (spread instruments filtered out)"
            )
        else:
            print("📊 Complete data: All instruments processed (including spreads)")

    except Exception as e:
        print(f"\n❌ ERROR: {e}")
        import traceback

        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
