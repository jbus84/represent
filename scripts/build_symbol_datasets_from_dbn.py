#!/usr/bin/env python3
"""
Build Symbol Datasets from DBN Files with Labels

This script implements the symbol-split-merge approach to create comprehensive
symbol datasets from multiple DBN files, with all original DBN columns plus
the new target labels generated by the specified labeling approach.

Usage:
    python scripts/build_symbol_datasets_from_dbn.py --preset mfe_analysis --dbn-dir /path/to/dbn/files --output-dir /path/to/output
    python scripts/build_symbol_datasets_from_dbn.py --config config.yaml --dbn-dir /path/to/dbn/files --output-dir /path/to/output
"""

